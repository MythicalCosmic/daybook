// Generates the CRM's bundled assets so the app works fully offline:
//   crm/app/src/ui/icons_gen.rs  - the Lucide icons we use (lucide-static, ISC licence)
//   crm/app/assets/fonts.css     - Figtree, Onest (Cyrillic) and Caprasimo as data: URIs (OFL)
//
// usage: node crm/tools/gen-assets.mjs <lucide-static/icons dir> <dashboard/node_modules dir>
// Add an icon: put its Lucide name in ICONS below and run the script again.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [iconsDir, nodeModules] = process.argv.slice(2);
if (!iconsDir || !nodeModules) {
  console.error("usage: node gen-assets.mjs <lucide icons dir> <node_modules dir>");
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(here, "..", "app");

