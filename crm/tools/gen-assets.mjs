const uniq = [...new Set(ICONS)];
const missing = [];
const arms = [];
for (const name of uniq) {
  const file = path.join(iconsDir, `${name}.svg`);
  if (!fs.existsSync(file)) { missing.push(name); continue; }
  const svg = fs.readFileSync(file, "utf8");
  const open = svg.indexOf(">", svg.indexOf("<svg"));
  const close = svg.lastIndexOf("</svg>");
  const inner = svg.slice(open + 1, close).replace(/\s+/g, " ").replace(/> </g, "><").trim();
  if (inner.includes('"#')) throw new Error(`icon ${name} breaks a raw string`);
  arms.push(`        "${name}" => r#"${inner}"#,`);
}

const rs = `// Generated by crm/tools/gen-assets.mjs from lucide-static (ISC licence). Do not edit by hand.
// ${arms.length} icons. Add names to ICONS in the script and run it again.

/// Inner SVG markup (24x24 viewBox, stroke icons) for a Lucide icon name; empty when unknown.
pub fn icon_svg(name: &str) -> &'static str {
    match name {
${arms.join("\n")}
        _ => "",
    }
}

/// Every bundled icon name (used by the icon gallery in Settings > About).
pub const ICON_NAMES: &[&str] = &[${uniq.filter((n) => !missing.includes(n)).map((n) => `"${n}"`).join(", ")}];
`;
fs.mkdirSync(path.join(appDir, "src", "ui"), { recursive: true });
fs.writeFileSync(path.join(appDir, "src", "ui", "icons_gen.rs"), rs);

// ---- fonts
function face(family, file, weight, unicodeRange) {
  const data = fs.readFileSync(file).toString("base64");
  return `@font-face{font-family:"${family}";font-style:normal;font-display:swap;font-weight:${weight};` +
    `src:url(data:font/woff2;base64,${data}) format("woff2");unicode-range:${unicodeRange};}`;
}
const LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";
const LATIN_EXT = "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF";
const CYR = "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116";
const CYR_EXT = "U+0460-052F,U+1C80-1C8A,U+20B4,U+2DE0-2DFF,U+A640-A69F,U+FE2E-FE2F";
const fv = (pkg, f) => path.join(nodeModules, "@fontsource-variable", pkg, "files", f);
const fs4 = (pkg, f) => path.join(nodeModules, "@fontsource", pkg, "files", f);
const faces = [
  face("Figtree", fv("figtree", "figtree-latin-wght-normal.woff2"), "300 900", LATIN),
  face("Figtree", fv("figtree", "figtree-latin-ext-wght-normal.woff2"), "300 900", LATIN_EXT),
  face("Onest", fv("onest", "onest-cyrillic-wght-normal.woff2"), "100 900", CYR),
  face("Onest", fv("onest", "onest-cyrillic-ext-wght-normal.woff2"), "100 900", CYR_EXT),
  face("Caprasimo", fs4("caprasimo", "caprasimo-latin-400-normal.woff2"), "400", LATIN),
];
fs.mkdirSync(path.join(appDir, "assets"), { recursive: true });
fs.writeFileSync(path.join(appDir, "assets", "fonts.css"),
  "/* Generated by crm/tools/gen-assets.mjs: Figtree, Onest and Caprasimo (SIL Open Font License). */\n" + faces.join("\n") + "\n");

