"""Write the dashboard's permission codes (`dashboard/src/core/perms.generated.ts`) from the
`Perm` registry, so the console's `Perm` type can never name a code the backend doesn't have.

`make perms-ts` runs it; `--check` only reports whether the file is up to date.
"""

import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from apps.members.permissions import Perm

DEFAULT_FILE = Path(settings.ROOT_DIR) / "dashboard" / "src" / "core" / "perms.generated.ts"


def render() -> str:
    codes = "".join(f"  {json.dumps(str(perm))},\n" for perm in Perm)
    return (
        "// Generated by `make perms-ts` from backend/apps/members/permissions.py. Do not edit.\n"
        "\n"
        f"export const PERMS = [\n{codes}] as const;\n"
        "\n"
        "export type Perm = (typeof PERMS)[number];\n"
    )


class Command(BaseCommand):
    help = "Write the dashboard's permission codes from the Perm registry."

    def add_arguments(self, parser):
        parser.add_argument("--file", type=Path, default=DEFAULT_FILE)
        parser.add_argument(
            "--check", action="store_true", help="Fail when the file is missing or out of date."
        )

    def handle(self, *args, file: Path, check=False, **options):
        content = render()
        if check:
            if not file.is_file() or file.read_text(encoding="utf-8") != content:
                raise CommandError(f"{file} is out of date: run `make perms-ts`.")
            self.stdout.write(f"{file} is up to date.")
            return
        if not file.parent.is_dir():
            raise CommandError(f"{file.parent} doesn't exist (is the dashboard checked out?).")
        file.write_text(content, encoding="utf-8")
        self.stdout.write(self.style.SUCCESS(f"Wrote {len(Perm)} permissions to {file}."))
