VS16, KEYCAP, ZWJ, NBSP = chr(0xFE0F), chr(0x20E3), chr(0x200D), chr(0xA0)


def _class(ranges) -> str:
    return "".join(
        re.escape(chr(low)) + (f"-{re.escape(chr(high))}" if high != low else "")
        for low, high in ranges
    )


_EMOJI_CHARS = _class(PICTOGRAPHIC + SEQUENCE_PARTS)
EMOJI = re.compile(f"[{_EMOJI_CHARS}]")
EMOJI_OR_SUBSTITUTE = re.compile(f"[{_EMOJI_CHARS}{re.escape(SUBSTITUTES)}]")
# One emoji as people see it, a keycap or pictographs joined by ZWJ with their selectors and
# skin tones, with the spaces around it.
_SPACE = f"[ \t{NBSP}]*"
_CLUSTER = re.compile(
    f"(?P<before>{_SPACE})"
    f"(?P<emoji>[0-9#*]{VS16}?{KEYCAP}|[{_EMOJI_CHARS}{ZWJ}]+)"
    f"(?P<after>{_SPACE})"
)
_SPACES = re.compile(r"\s+")


def has_emoji(text: str | None) -> bool:
    return bool(text) and EMOJI_OR_SUBSTITUTE.search(text) is not None


def strip_emoji(text: str) -> str:
    """`text` without emoji. At the start of a line an emoji goes with the space after it
    ("✅ Done" becomes "Done"), at the end with the space before it, between words it leaves
    one space."""

    def replace(match: re.Match) -> str:
        start, end = match.start(), match.end()
        line_start = start == 0 or text[start - 1] == "\n"
        line_end = end == len(text) or text[end] == "\n"
        if line_end:
            return ""
        if line_start:
            return match["before"]  # the line's indentation
        return " " if match["before"] and match["after"] else ""

    return _CLUSTER.sub(replace, text)


def plain_label(text: str | None) -> str:
    """A keyboard label as the bot compares it: without emoji, its spaces collapsed."""
    return _SPACES.sub(" ", strip_emoji(text or "")).strip()
